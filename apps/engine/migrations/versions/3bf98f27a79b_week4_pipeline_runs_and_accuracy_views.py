# One row per (model, finished match) with an official (pre-kick-off) prediction. Scores match
# engine.evaluate.metrics: log loss clipped at 1e-15, RPS over home < draw < away halved to [0, 1],
# multi-class Brier in [0, 2]; ``predicted`` breaks argmax ties towards H, then D, like np.argmax.
PREDICTION_SCORES = """
CREATE VIEW prediction_scores AS
SELECT o.model, o.match_id, o.model_run_id, o.prediction_id,
       s.label AS season, m.stage, m.matchday, m.match_date, m.kickoff_utc,
       m.home_team_id, m.away_team_id, m.home_goals_90, m.away_goals_90,
       o.p_home, o.p_draw, o.p_away,
       y.outcome,
       CASE WHEN o.p_home >= o.p_draw AND o.p_home >= o.p_away THEN 'H'
            WHEN o.p_draw >= o.p_away THEN 'D'
            ELSE 'A' END AS predicted,
       -ln(GREATEST(CASE y.outcome WHEN 'H' THEN o.p_home WHEN 'D' THEN o.p_draw
                                   ELSE o.p_away END, 1e-15)) AS log_loss,
       ((o.p_home - y.h) ^ 2 + (o.p_home + o.p_draw - y.h - y.d) ^ 2) / 2 AS rps,
       (o.p_home - y.h) ^ 2 + (o.p_draw - y.d) ^ 2 + (o.p_away - y.a) ^ 2 AS brier
FROM official_predictions o
JOIN matches m ON m.id = o.match_id
JOIN seasons s ON s.id = m.season_id
CROSS JOIN LATERAL (
    SELECT x.outcome,
           (x.outcome = 'H')::int AS h, (x.outcome = 'D')::int AS d, (x.outcome = 'A')::int AS a
    FROM (SELECT CASE WHEN m.home_goals_90 > m.away_goals_90 THEN 'H'
                      WHEN m.home_goals_90 = m.away_goals_90 THEN 'D'
                      ELSE 'A' END AS outcome) x
) y
WHERE m.status = 'FINISHED'
  AND m.home_goals_90 IS NOT NULL AND m.away_goals_90 IS NOT NULL
"""

# Per (model, season), plus a uniform 1/3 forecast on the same matches: its log loss is ln 3, Brier
# 2/3, RPS 1/9 for a draw and 5/18 otherwise, and its argmax is H (np.argmax tie-break).
MODEL_SCOREBOARD = """
CREATE VIEW model_scoreboard AS
SELECT model, season,
       count(*) AS n,
       avg(log_loss) AS log_loss,
       avg(rps) AS rps,
       avg(brier) AS brier,
       avg((predicted = outcome)::int) AS accuracy,
       ln(3::float8) AS uniform_log_loss,
       avg(CASE WHEN outcome = 'D' THEN 1 / 9::float8 ELSE 5 / 18::float8 END) AS uniform_rps,
       2 / 3::float8 AS uniform_brier,
       avg((outcome = 'H')::int) AS uniform_accuracy
FROM prediction_scores
GROUP BY model, season
"""


