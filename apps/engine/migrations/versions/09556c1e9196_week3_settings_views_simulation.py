_KICKOFF = "COALESCE(m.kickoff_utc, m.match_date::timestamp AT TIME ZONE 'UTC')"

# Per (model, match): the latest prediction created before kick-off. Models never shadow each other.
OFFICIAL_PREDICTIONS = f"""
CREATE VIEW official_predictions AS
SELECT DISTINCT ON (r.model, p.match_id)
       p.id AS prediction_id, p.match_id, p.model_run_id, r.model,
       p.p_home, p.p_draw, p.p_away, p.created_at
FROM predictions p
JOIN matches m ON m.id = p.match_id
JOIN model_runs r ON r.id = p.model_run_id
WHERE p.created_at < {_KICKOFF}
ORDER BY r.model, p.match_id, p.created_at DESC, p.id DESC
"""

