# Per match, the latest prediction created before kick-off (NULL kick-off: match_date 00:00 UTC).
# Later rows, e.g. from a run after kick-off, never displace it.
OFFICIAL_PREDICTIONS = """
CREATE VIEW official_predictions AS
SELECT DISTINCT ON (p.match_id)
       p.id AS prediction_id, p.match_id, p.model_run_id, r.model,
       p.p_home, p.p_draw, p.p_away, p.created_at
FROM predictions p
JOIN matches m ON m.id = p.match_id
JOIN model_runs r ON r.id = p.model_run_id
WHERE p.created_at < COALESCE(m.kickoff_utc, m.match_date::timestamp AT TIME ZONE 'UTC')
ORDER BY p.match_id, p.created_at DESC, p.id DESC
"""


